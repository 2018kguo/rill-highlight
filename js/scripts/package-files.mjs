// Writes the files the npm package carries besides src/ and dist/: README.md and
// LICENSE (copied from the repository root), and THIRD_PARTY_NOTICES.md (also
// written to the root) from the license fields of tm-grammars and tm-themes, the
// packages Shiki builds its bundled grammars and themes from, plus the licenses
// of the code rill-highlight ports. The full upstream license texts are the
// packages' NOTICE files, copied to notices/.
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { grammars, injections } from 'tm-grammars';
import { themes } from 'tm-themes';

const here = new URL('..', import.meta.url).pathname;
const packageDir = (name) => `${here}node_modules/${name}/`;
const version = (name) => JSON.parse(readFileSync(packageDir(name) + 'package.json', 'utf8')).version;
const licenseText = (name, file = 'LICENSE') => readFileSync(packageDir(name) + file, 'utf8').trim();

const byName = new Map([...grammars, ...injections].map((grammar) => [grammar.name, grammar]));
const themeByName = new Map(themes.map((theme) => [theme.name, theme]));
const names = (dir) => readdirSync(here + dir).map((file) => file.replace(/\.json$/, '')).sort();
const row = (name, entry) => {
  if (!entry) throw new Error(`${name}: not in tm-grammars/tm-themes, so its license is unknown`);
  const license = entry.license ? (entry.licenseUrl ? `[${entry.license}](${entry.licenseUrl})` : entry.license) : 'not stated';
  return `| ${name} | ${license} | ${entry.source} |`;
};

const ported = [
  ['shiki', 'LICENSE', 'Shiki: the highlighting pipeline (`codeToTokens`, `codeToHtml`, theme normalization, the JavaScript regex engine scanner) that src/ and js/src/ port.'],
  ['@shikijs/vscode-textmate', 'LICENSE.md', "Shiki's fork of vscode-textmate: the TextMate tokenizer, theme matching and scope selectors ported in src/textmate/."],
  ['oniguruma-to-es', 'LICENSE', 'The Oniguruma-to-JavaScript pattern translation the grammar files contain, and the `EmulatedRegExp` semantics src/regex/ implements.'],
  ['@streamdown/code', 'LICENSE', "Streamdown's code plugin: the caching and incremental tokenization in js/src/streamdown.js."],
];

const text = `# Third-party notices

rill-highlight is MIT-licensed (see LICENSE). It ports code from the projects
below and ships grammars and themes written by others. Generated by
js/scripts/build-notices.mjs; do not edit.

## Ported code

${ported.map(([name, file, what]) => `### ${name} ${version(name)}\n\n${what}\n\n\`\`\`\n${licenseText(name, file)}\n\`\`\``).join('\n\n')}

## Grammars

The ${names('dist/grammars').length} grammars in dist/data/grammars/ are Shiki ${version('shiki')}'s bundled
grammars, from tm-grammars ${version('tm-grammars')}, converted (their patterns translated
to JavaScript syntax). Each keeps its own license, listed here from
tm-grammars' metadata; the license texts are in notices/tm-grammars-NOTICE (in
the npm package, copied from tm-grammars).
Some are GPL-3.0 or MPL-2.0 licensed: if that matters for your distribution,
leave those grammars out of what you serve.

| Grammar | License | Source |
| --- | --- | --- |
${names('dist/grammars').map((name) => row(name, byName.get(name))).join('\n')}

## Themes

The ${names('dist/themes').length} themes in dist/data/themes/ are Shiki ${version('shiki')}'s bundled themes, from
tm-themes ${version('tm-themes')}, unchanged. The license texts are in
notices/tm-themes-NOTICE.

| Theme | License | Source |
| --- | --- | --- |
${names('dist/themes').map((name) => row(name, themeByName.get(name))).join('\n')}
`;

mkdirSync(here + 'notices', { recursive: true });
copyFileSync(packageDir('tm-grammars') + 'NOTICE', here + 'notices/tm-grammars-NOTICE');
copyFileSync(packageDir('tm-themes') + 'NOTICE', here + 'notices/tm-themes-NOTICE');
writeFileSync(here + 'THIRD_PARTY_NOTICES.md', text);
writeFileSync(here + '../THIRD_PARTY_NOTICES.md', text);
for (const file of ['README.md', 'LICENSE']) copyFileSync(here + '../' + file, here + file);
console.log(`THIRD_PARTY_NOTICES.md: ${byName.size} grammars, ${themeByName.size} themes listed`);
